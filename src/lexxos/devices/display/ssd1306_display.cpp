char normalizeGlyph(char value) {
	if (value >= 'a' && value <= 'z') {
		return static_cast<char>(value - 'a' + 'A');
	}
	return value;
}

std::array<std::uint8_t, oledFontWidth> const& glyphColumns(char value) {
	char const normalized = normalizeGlyph(value);
	for (auto const& glyph : font) {
		if (glyph.value == normalized) {
			return glyph.columns;
		}
	}
	return font[0].columns;
}

