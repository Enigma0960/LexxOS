#!/usr/bin/env python3
"""Convert a TTF/OTF font to a compact, embedded LexxOS bitmap header.

Uses Pillow's FreeType backend on the development host; no font engine is
needed on embedded targets. No TTF/OTF data is copied into output.
"""
from __future__ import annotations

import argparse
from pathlib import Path


def codepoints(spec: str) -> list[int]:
    """Ranges: U+0020-U+007E,U+0401,U+0410-U+044F,U+0451."""
    found: set[int] = set()
    for token in spec.split(","):
        parts = token.strip().upper().split("-")
        if not 1 <= len(parts) <= 2:
            raise ValueError(f"invalid character range: {token}")
        def parse(value: str) -> int:
            return int(value[2:], 16) if value.startswith("U+") else int(value, 16)
        start = parse(parts[0])
        end = parse(parts[-1])
        if start > end or end > 0x10FFFF or end - start > 4096:
            raise ValueError(f"invalid character range: {token}")
        found.update(range(start, end + 1))
    return sorted(found)


def rasterize(font_path: Path, size: int, width: int, height: int, chars: list[int], threshold: int = 110):
    from PIL import Image, ImageDraw, ImageFont

    font = ImageFont.truetype(str(font_path), size)
    # Fixed baseline allows letters with descenders to align correctly.
    baseline = height - 3
    glyphs = []
    for code in chars:
        image = Image.new("L", (width, height), 0)
        draw = ImageDraw.Draw(image)
        draw.text((0, baseline), chr(code), fill=255, font=font, anchor="ls")
        rows = []
        for y in range(height):
            value = 0
            for x in range(width):
                if image.getpixel((x, y)) >= threshold:
                    value |= 1 << x
            rows.append(value)
        glyphs.append((code, rows))
    return glyphs


def header(glyphs, width: int, height: int, name: str, source: str, license_id: str) -> str:
    if width > 16 or height > 32:
        raise ValueError("C++ header supports glyphs up to 16x32")
    lines = [
        "// Generated by tools/lexx_font_pack.py. Do not edit manually.",
        f"// Source: {source}",
        f"// Font license: {license_id}. Preserve the upstream copyright and license notice.",
        "#pragma once", "", "#include <array>", "#include <cstdint>", "",
        "namespace lexxos::ui::font {", "",
        f"inline constexpr unsigned cellWidth = {width}U;",
        f"inline constexpr unsigned cellHeight = {height}U;",
        "struct Glyph {", "\tstd::uint32_t codepoint;", f"\tstd::array<std::uint16_t, {height}> bitmap;", "};", "",
        f"inline constexpr std::array<Glyph, {len(glyphs)}> {name} = {{{{",
    ]
    for cp, rows in glyphs:
        bitmap = ", ".join(f"0x{x:04X}U" for x in rows)
        lines.append(f"\t{{0x{cp:04X}U, {{{{{bitmap}}}}}}},")
    lines.extend(["}};", "", "} // namespace lexxos::ui::font", ""])
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path, help="input TTF/OTF file")
    parser.add_argument("output", type=Path, help="output generated .h")
    parser.add_argument("--size", type=int, default=13, help="FreeType pixel size")
    parser.add_argument("--cell", default="9x16", help="glyph cell size; max 16x32")
    parser.add_argument("--chars", default="U+0020-U+007E,U+0401,U+0410-U+044F,U+0451")
    parser.add_argument("--name", default="defaultGlyphs", help="C++ identifier")
    parser.add_argument("--license", default="SIL OFL 1.1", help="upstream font license label")
    args = parser.parse_args(argv)
    try:
        w, h = [int(item) for item in args.cell.lower().split("x")]
        if not 1 <= w <= 16 or not 1 <= h <= 32 or not 1 <= args.size <= 128:
            raise ValueError("invalid glyph dimensions or pixel size")
        if not args.name.isidentifier():
            raise ValueError("name must be a C++ identifier")
        chars = codepoints(args.chars)
        glyphs = rasterize(args.font, args.size, w, h, chars)
        result = header(glyphs, w, h, args.name, args.font.name, args.license)
    except (ValueError, OSError, ImportError) as exc:
        parser.error(str(exc))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(result, encoding="utf-8")
    print(f"{len(chars)} glyphs, {w}x{h}: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
